#!/usr/bin/env python3
"""Export jankcraft's runtime card data to Lua.

    python3 tools/export_data.py [--force]

Writes:
  Data/Cards.lua             every card the engine can touch (implemented cards + referenced tokens),
                             in the engine's id order, for both the UI and the engine
  Engine/Data/Programs.lua   each implemented card's effect lists, default fields stripped

Order matters: the engine's random pools walk the catalogue in id order, so the Lua side keeps
TC.CardOrder exactly as written here and never re-sorts ids at runtime (Lua string comparison
can follow the host locale; Python's is bytewise, like std::string's).
"""
import sys

from common import WORDING_FIELDS, is_default, load_runtime, lua_string, lua_value, write, ensure_dumps

CHUNK = 250  # cards per Lua function, to stay far below per-function constant limits

FLAG_COLLECTIBLE, FLAG_DROPPABLE, FLAG_IMPLEMENTED, FLAG_PLAYABLE = 1, 2, 4, 8

# Program-level keys that are not runtime data for the Lua engine.
PROGRAM_SKIP = {"program", "implemented", "displayText", "approximate"}
EFFECT_SKIP = {"wording", "sourcePhrase", "tokenDisplay"}


def strip_effect(effect):
    out = {}
    for k, v in effect.items():
        if k in EFFECT_SKIP:
            continue
        if k in ("followUp", "replacement"):
            v = [strip_effect(e) for e in v]
            if v:
                out[k] = v
            continue
        if k == "target":
            out[k] = v
            continue
        if not is_default(k, v):
            out[k] = v
    return out


def referenced_ids(value, known, found):
    """Every string inside `value` that names a known card."""
    if isinstance(value, str):
        if value in known:
            found.add(value)
    elif isinstance(value, list):
        for v in value:
            referenced_ids(v, known, found)
    elif isinstance(value, dict):
        for k, v in value.items():
            if k not in WORDING_FIELDS and k not in ("program", "displayText"):
                referenced_ids(v, known, found)


def main():
    if "--force" in sys.argv:
        ensure_dumps(force=True)
    cards, programs_doc, playable = load_runtime()
    programs = programs_doc["programs"]
    by_id = {c["id"]: c for c in cards}
    playable_set = set(playable)

    # The engine set: implemented cards, plus every card they (transitively) name.
    keep = {cid for cid, c in by_id.items() if c["implemented"]}
    frontier = list(keep)
    while frontier:
        cid = frontier.pop()
        found = set()
        referenced_ids(programs.get(cid, {}), by_id, found)
        for ref in found - keep:
            keep.add(ref)
            frontier.append(ref)
    order = sorted(keep)  # bytewise, matching std::string ordering for these ASCII ids

    # ---- Data/Cards.lua -------------------------------------------------------------------------
    lines = [
        "-- GENERATED by tools/export_data.py from jankcraft's runtime catalogue. Do not edit.",
        "-- %d cards (%d playable). Flags: 1 collectible, 2 droppable, 4 implemented, 8 playable (packs/quests)."
        % (len(order), len(playable_set & keep)),
        "local TC = TavernCards_NS",
        "local cards, order = {}, {}",
        "TC.Cards, TC.CardOrder = cards, order",
        "local function C(id, name, ctype, family, rarity, school, cost, attack, health, durability, keywords, races, flags, text, shown)",
        "    cards[id] = { id = id, name = name, type = ctype, family = family, rarity = rarity, school = school,",
        "        cost = cost, attack = attack, health = health, durability = durability, keywords = keywords,",
        "        races = races, flags = flags, text = text, shown = shown }",
        "    order[#order + 1] = id",
        "end",
    ]
    for start in range(0, len(order), CHUNK):
        lines.append("do (function()")
        for cid in order[start:start + CHUNK]:
            c = by_id[cid]
            flags = ((FLAG_COLLECTIBLE if c["collectible"] else 0) | (FLAG_DROPPABLE if c["droppable"] else 0)
                     | (FLAG_IMPLEMENTED if c["implemented"] else 0) | (FLAG_PLAYABLE if cid in playable_set else 0))
            shown = programs.get(cid, {}).get("displayText")
            args = [cid, c["name"], c["type"], c["family"], c["rarity"], c["school"], c["cost"], c["attack"],
                    c["health"], c["durability"], c["keywords"], c["races"], flags, c["text"]]
            if shown and shown != c["text"]:
                args.append(shown)
            lines.append("C(" + ",".join(lua_value(a) for a in args) + ")")
        lines.append("end)() end")
    write("Data/Cards.lua", "\n".join(lines) + "\n")

    # ---- Engine/Data/Programs.lua ---------------------------------------------------------------
    lines = [
        "-- GENERATED by tools/export_data.py from jankcraft's runtime programs (lowered). Do not edit.",
        "local TC = TavernCards_NS",
        "local P = {}",
        "TC.Programs = P",
        "TC.RULES_VERSION = " + lua_string(programs_doc["rulesVersion"]),
    ]
    ids = [cid for cid in order if cid in programs]
    for start in range(0, len(ids), CHUNK):
        lines.append("do (function()")
        for cid in ids[start:start + CHUNK]:
            prog = {}
            for k, v in programs[cid].items():
                if k in PROGRAM_SKIP:
                    continue
                if k == "effects":
                    v = [strip_effect(e) for e in v]
                elif k == "choices":
                    v = [[strip_effect(e) for e in option] for option in v]
                if not is_default(k, v):
                    prog[k] = v
            lines.append("P[" + lua_string(cid) + "]=" + lua_value(prog))
        lines.append("end)() end")
    write("Engine/Data/Programs.lua", "\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
